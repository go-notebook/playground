// Command genwrap writes symbols/zz_generics.go: the generic functions of
// go-statistics/stats, instantiated so that the interpreter can call them.
//
// yaegi cannot export a generic function — there is no value to export until
// its type parameters are fixed — so `yaegi extract` leaves out every one of
// them, and stats is mostly generic: Mean[D Data], FitNormal[D Data], ... For
// each function whose type parameters are all constrained by stats.Data
// (= []float64 | *ndarray.Array), genwrap writes a wrapper where
//
//   - a parameter of type D (or ...D) is an `any`, converted by symbols.Data:
//     a []float64 or a *ndarray.Array of any shape and dtype, read in
//     row-major order, as stats itself reads it;
//   - every other use of D ([]D, a result D) is []float64.
//
// A function with another kind of type parameter is reported and left out.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// statsPath is the package whose generic functions are wrapped.
const statsPath = "github.com/go-statistics/stats"

var (
	// goList finds a package's directory; a variable so a test can point
	// it elsewhere.
	goList = func(pkg string) (string, error) {
		out, err := exec.Command("go", "list", "-f", "{{.Dir}}", pkg).Output()
		return strings.TrimSpace(string(out)), err
	}
	stderr       io.Writer = os.Stderr
	exit                   = os.Exit
	formatSource           = format.Source
)

func main() {
	out := flag.String("o", "zz_generics.go", "output file")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(stderr, "genwrap:", err)
		exit(1)
	}
}

func run(out string) error {
	dir, err := goList(statsPath)
	if err != nil {
		return fmt.Errorf("go list %s: %w", statsPath, err)
	}
	src, skipped, err := generate(dir)
	if err != nil {
		return err
	}
	for _, s := range skipped {
		fmt.Fprintln(stderr, "genwrap: left out", s)
	}
	return os.WriteFile(out, src, 0o644)
}

// wrapper is one generated function.
type wrapper struct {
	name string
	code string
}

// generate reads the package in dir and returns the generated file, and the
// generic functions it could not wrap, with the reason.
func generate(dir string) ([]byte, []string, error) {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, nil, err
	}
	var ws []wrapper
	var skipped []string
	imports := map[string]string{} // package name -> path, as the sources import them
	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, nil, err
		}
		local := map[string]string{}
		for _, im := range f.Imports {
			p := strings.Trim(im.Path.Value, `"`)
			n := filepath.Base(p)
			if im.Name != nil {
				n = im.Name.Name
			}
			local[n] = p
		}
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv != nil || !fd.Name.IsExported() || fd.Type.TypeParams == nil {
				continue
			}
			w, used, why := wrap(fset, fd)
			if why != "" {
				skipped = append(skipped, fd.Name.Name+": "+why)
				continue
			}
			for _, u := range used {
				imports[u] = local[u]
			}
			ws = append(ws, w)
		}
	}
	sort.Slice(ws, func(i, j int) bool { return ws[i].name < ws[j].name })
	sort.Strings(skipped)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/genwrap. DO NOT EDIT.\n\npackage symbols\n\nimport (\n\t\"reflect\"\n\n")
	var names []string
	for n := range imports {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if filepath.Base(imports[n]) == n {
			fmt.Fprintf(&b, "\t%q\n", imports[n])
		} else {
			fmt.Fprintf(&b, "\t%s %q\n", n, imports[n])
		}
	}
	fmt.Fprintf(&b, "\t%q\n)\n\n", statsPath)
	b.WriteString("// The generic functions of stats, instantiated: see internal/genwrap.\nfunc init() {\n")
	fmt.Fprintf(&b, "\tm := pkg(%q)\n", statsPath+"/stats")
	for _, w := range ws {
		b.WriteString(w.code)
	}
	b.WriteString("}\n")
	src, err := formatSource(b.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("generated code: %w", err)
	}
	return src, skipped, nil
}

// wrap writes the wrapper of fd, and the packages its signature names; why
// says why it cannot.
func wrap(fset *token.FileSet, fd *ast.FuncDecl) (wrapper, []string, string) {
	tparams := map[string]bool{}
	var targs []string
	for _, f := range fd.Type.TypeParams.List {
		if id, ok := f.Type.(*ast.Ident); !ok || id.Name != "Data" {
			return wrapper{}, nil, "a type parameter is not constrained by Data"
		}
		for _, n := range f.Names {
			tparams[n.Name] = true
			targs = append(targs, "[]float64")
		}
	}
	used := map[string]bool{}
	// typ rewrites a type expression for the wrapper's signature: a type
	// parameter becomes []float64, a package-local name stats.Name.
	var bad string
	var typ func(e ast.Expr) ast.Expr
	typ = func(e ast.Expr) ast.Expr {
		switch t := e.(type) {
		case *ast.Ident:
			switch {
			case tparams[t.Name]:
				return &ast.ArrayType{Elt: ast.NewIdent("float64")}
			case t.IsExported():
				return &ast.SelectorExpr{X: ast.NewIdent("stats"), Sel: ast.NewIdent(t.Name)}
			case !isPredeclared(t.Name):
				bad = "its signature names the unexported " + t.Name
			}
			return ast.NewIdent(t.Name) // without the source's position
		case *ast.SelectorExpr:
			x := t.X.(*ast.Ident).Name
			used[x] = true
			return &ast.SelectorExpr{X: ast.NewIdent(x), Sel: ast.NewIdent(t.Sel.Name)}
		case *ast.StarExpr:
			return &ast.StarExpr{X: typ(t.X)}
		case *ast.ArrayType:
			return &ast.ArrayType{Len: t.Len, Elt: typ(t.Elt)}
		case *ast.Ellipsis:
			return &ast.Ellipsis{Elt: typ(t.Elt)}
		case *ast.MapType:
			return &ast.MapType{Key: typ(t.Key), Value: typ(t.Value)}
		case *ast.FuncType:
			return &ast.FuncType{Params: fields(t.Params, typ), Results: fields(t.Results, typ)}
		}
		bad = fmt.Sprintf("its signature has a %T", e)
		return e
	}

	var params, args []string
	n := 0
	for _, f := range fd.Type.Params.List {
		names := f.Names
		if len(names) == 0 {
			names = []*ast.Ident{nil}
		}
		for _, id := range names {
			name := fmt.Sprintf("p%d", n)
			if id != nil && id.Name != "_" {
				name = id.Name
			}
			n++
			switch t := f.Type.(type) {
			case *ast.Ident:
				if tparams[t.Name] {
					params = append(params, name+" any")
					args = append(args, "Data("+name+")")
					continue
				}
			case *ast.Ellipsis:
				if id, ok := t.Elt.(*ast.Ident); ok && tparams[id.Name] {
					params = append(params, name+" ...any")
					args = append(args, "DataAll("+name+")...")
					continue
				}
			}
			params = append(params, name+" "+expr(fset, typ(f.Type)))
			arg := name
			if _, ok := f.Type.(*ast.Ellipsis); ok {
				arg += "..."
			}
			args = append(args, arg)
		}
	}
	results := ""
	if fd.Type.Results != nil {
		results = expr(fset, &ast.FuncType{Params: &ast.FieldList{}, Results: fields(fd.Type.Results, typ)})
		results = strings.TrimPrefix(results, "func()")
	}
	if bad != "" {
		return wrapper{}, nil, bad
	}
	ret := "return "
	if results == "" {
		ret = ""
	}
	code := fmt.Sprintf("\tm[%q] = reflect.ValueOf(func(%s)%s { %sstats.%s[%s](%s) })\n",
		fd.Name.Name, strings.Join(params, ", "), results, ret, fd.Name.Name, strings.Join(targs, ", "), strings.Join(args, ", "))
	var pk []string
	for p := range used {
		pk = append(pk, p)
	}
	sort.Strings(pk)
	return wrapper{name: fd.Name.Name, code: code}, pk, ""
}

// fields rewrites the types of a field list.
func fields(l *ast.FieldList, typ func(ast.Expr) ast.Expr) *ast.FieldList {
	if l == nil {
		return nil
	}
	out := &ast.FieldList{}
	for _, f := range l.List {
		var names []*ast.Ident
		for _, n := range f.Names {
			names = append(names, ast.NewIdent(n.Name)) // without the source's positions
		}
		out.List = append(out.List, &ast.Field{Names: names, Type: typ(f.Type)})
	}
	return out
}

func expr(fset *token.FileSet, e ast.Node) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, e) // printing to memory cannot fail
	return b.String()
}

func isPredeclared(name string) bool {
	switch name {
	case "bool", "byte", "complex64", "complex128", "error", "float32", "float64",
		"int", "int8", "int16", "int32", "int64", "rune", "string",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "any":
		return true
	}
	return false
}
